    public static String body(String lang, int cursor) {
        String[] openings = EN_OPEN, invitations = EN_INVITE;
        if (lang != null) switch (lang) {
            case "ms": openings = MS_OPEN; invitations = MS_INVITE; break;
            case "zh": openings = ZH_OPEN; invitations = ZH_INVITE; break;
            case "zh-Hant": openings = ZH_HANT_OPEN; invitations = ZH_HANT_INVITE; break;
            case "ja": openings = JA_OPEN; invitations = JA_INVITE; break;
            case "ta": openings = TA_OPEN; invitations = TA_INVITE; break;
            default: break;
        }
        int index = normalize(cursor), opening = index % 40;
        int invitation = (index / 40 + opening) % 25;
        return openings[opening] + " " + invitations[invitation];
    }
